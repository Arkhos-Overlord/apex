def instruct(
    teacher_name: str, topic: str, learner_state: LearnerState | None = None
) -> LessonContent:
    """Generate personality-tailored lesson content for a teacher and topic.

    Uses the teacher's profile to shape the greeting, explanation style,
    questions, practice exercises, and encouragement. If learner_state is
    provided and contains errors, corrective guidance is woven into the output.

    Args:
        teacher_name: Name of the teacher (case-insensitive).
        topic: The topic to generate instruction for.
        learner_state: Optional learner state; errors trigger corrective feedback.

    Returns:
        A LessonContent instance with all fields populated.
    """
    teacher = get_teacher(teacher_name)
    base = _generate_content(teacher, topic, learner_state)

    # Generate Socratic questions
    questions = generate_socratic_questions(teacher, topic)

    # Incorporate error diagnosis if applicable
    if learner_state and learner_state.errors:
        correction = diagnose_errors(teacher, learner_state.errors)
        # Prepend correction to the explanation for direct teachers,
        # append for others
        if teacher.teaching_style == "direct":
            base["explanation"] = f"{correction}\n\n{base['explanation']}"
        else:
            base["explanation"] = f"{base['explanation']}\n\n{correction}"

    # Build the lesson content
    return LessonContent(
        teacher_name=teacher.name,
        topic=topic,
        greeting=teacher.greeting,
        explanation=base["explanation"],
        example=base["example"],
        questions=questions,
        practice_exercises=base["practice_exercises"],
        encouragement=base["encouragement"],
        tts_voice=get_tts_voice(teacher),
    )

