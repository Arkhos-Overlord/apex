_VOICE_MAP: dict[str, str] = {
    "alloy": "alloy",
    "shimmer": "shimmer",
    "nova": "nova",
    "fable": "fable",
    "echo": "echo",
    "onyx": "onyx",
}


def get_tts_voice(teacher: TeacherProfile) -> str:
    """Map a teacher's voice preference to an actual TTS voice identifier.

    Args:
        teacher: The teacher whose voice to resolve.

    Returns:
        A TTS voice identifier string suitable for speech synthesis.
    """
    preferred = teacher.voice.lower().strip()
    return _VOICE_MAP.get(preferred, "alloy")


