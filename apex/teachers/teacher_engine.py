"""Personality-aware instruction engine for APEX teachers.

Generates tailored lesson content based on teacher profiles and learner state.
"""

from __future__ import annotations

from collections.abc import Callable
from dataclasses import dataclass, field
from typing import Any

from apex.teachers.teacher_config import TeacherProfile, get_teacher


@dataclass
class LearnerState:
    """Snapshot of a learner's current state during instruction.

    Attributes:
        current_topic: The topic currently being studied.
        errors: Recent mistakes the learner has made.
        attempts: Number of attempts made on the current problem.
        confidence: Self-assessed confidence level from 0.0 (no confidence) to 1.0 (fully confident).
        pace: Preferred learning speed ('fast', 'normal', 'slow').
        preferred_teacher: Name of the learner's preferred teacher, or None.
    """

    current_topic: str = ""
    errors: list[str] = field(default_factory=list)
    attempts: int = 0
    confidence: float = 0.5
    pace: str = "normal"
    preferred_teacher: str | None = None


@dataclass
class LessonContent:
    """Complete lesson content generated by a teacher.

    Attributes:
        teacher_name: Name of the teacher who generated this content.
        topic: The lesson topic.
        greeting: Opening message from the teacher.
        explanation: Core explanatory content.
        example: Concrete example illustrating the concept.
        questions: Socratic or guiding questions to prompt learner thinking.
        practice_exercises: Exercises for the learner to practice.
        encouragement: Motivational closing message.
        tts_voice: TTS voice identifier for speech synthesis.
    """

    teacher_name: str
    topic: str
    greeting: str
    explanation: str
    example: str
    questions: list[str]
    practice_exercises: list[str]
    encouragement: str
    tts_voice: str


