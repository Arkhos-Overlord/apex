def generate_socratic_questions(teacher: TeacherProfile, topic: str, count: int = 3) -> list[str]:
    """Generate Socratic questions appropriate to the teacher's style.

    Args:
        teacher: The teacher profile whose style guides question generation.
        topic: The topic the questions should explore.
        count: Number of questions to generate (default 3).

    Returns:
        A list of Socratic questions tailored to the teacher and topic.
    """
    topic_key = topic.lower()
    pool = _FOUNDATION_QUESTIONS.get(
        topic_key,
        [
            f"What do you think {topic} is really about at its core?",
            f"How does {topic} connect to what you already know?",
            f"What would change if {topic} worked differently?",
            f"Why does {topic} matter in the bigger picture?",
            f"What question about {topic} still feels unanswered to you?",
        ],
    )

    # Different teachers ask questions differently
    if teacher.teaching_style == "socratic":
        # Mentor: open-ended, reflective, builds from learner's thinking
        selected = pool[:count]
        return [f"Reflect on this: {q}" for q in selected]

    if teacher.teaching_style == "direct":
        # Drill Sergeant: direct, challenging, demands answers
        selected = pool[:count]
        return [f"Answer directly: {q}" for q in selected]

    if teacher.teaching_style == "inquiry":
        # Guide: leading, exploratory, connects to resources
        selected = pool[:count]
        return [f"Explore this angle: {q}" for q in selected]

    # Storyteller or other: narrative, metaphor-driven
    selected = pool[:count]
    return [f"Imagine this: {q}" for q in selected]


# â”€â”€ Error diagnosis â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€â”€

_CORRECTION_TEMPLATES: dict[str, str] = {
    "socratic": (
        "I notice you ran into a challenge with {error}. That's actually a great learning moment. "
        "Let's think about what might have caused that. What did you expect to happen, and what actually happened? "
        "Often the gap between expectation and reality is where the real learning lives. "
        "Take a moment to trace through your logicâ€”what assumption might have led you astray?"
    ),
    "direct": (
        "Error detected: {error}. Here's the fixâ€”{correction}. "
        "You need to understand why that was wrong. The correct approach is {correct_approach}. "
        "Now repeat it until you get it right. No shortcuts."
    ),
    "inquiry": (
        "Interestingâ€”you encountered {error}. Let's unpack that together. "
        "What was your thinking when you wrote that code? There's usually a reasonable intuition behind a mistake. "
        "Let's look at what the code actually did versus what you intended. "
        "I'd suggest checking {resource} for a deeper dive into this area."
    ),
    "narrative": (
        "Ah, {error}â€”a twist in our story! Even the greatest programmers have stumbled here. "
        "Let me tell you about a time when a similar mistake taught someone an invaluable lesson. "
        "The lesson? {lesson}. So next time, remember: {wisdom}."
    ),
}


def diagnose_errors(teacher: TeacherProfile, errors: list[str]) -> str:
    """Analyze learner errors and produce corrective feedback in the teacher's voice.

    Args:
        teacher: The teacher whose voice and correction style to use.
        errors: A list of error descriptions from the learner's recent work.

    Returns:
        Corrective feedback string in the teacher's distinctive voice.
    """
    if not errors:
        return (
            "No errors to addressâ€”excellent work! Keep up this focused approach. "
            "If anything feels uncertain, remember that asking questions is a sign of engagement, not weakness."
        )

    # Use the first error as the primary focus, acknowledge others briefly
    primary_error = errors[0]
    extra_errors = errors[1:]

    template = _CORRECTION_TEMPLATES.get(
        teacher.teaching_style,
        _CORRECTION_TEMPLATES["socratic"],
    )

    if teacher.teaching_style == "narrative":
        # The Storyteller has one lesson and one piece of wisdom of its own.
        # (These were previously looked up in tables keyed by
        # teaching_style from inside the `== "narrative"` branch, so the
        # other three entries could never be reached.)
        result = template.format(
            error=primary_error,
            lesson="even mistakes are chapters in the larger story of mastery.",
            wisdom="every great story has a turning point, and this is yours.",
        )
        if extra_errors:
            result += f"\n\nAnd the road ahead has more trials still: {'; '.join(extra_errors)}."
        return result

    # For other styles, provide corrective guidance
    correction = _suggest_correction(primary_error)
    correct_approach = _suggest_correction(primary_error, focus_on_approach=True)
    resource = _suggest_resource(primary_error)

    result = template.format(
        error=primary_error,
        correction=correction,
        correct_approach=correct_approach,
        resource=resource,
    )

    if extra_errors:
        let_s_redirect = (
            "Let's tackle these one at a time."
            if teacher.patience_level in ("high", "medium")
            else "Address these now."
        )
        result += f"\n\nI also noticed: {'; '.join(extra_errors)}. {let_s_redirect}"

    return result


def _suggest_correction(error: str, focus_on_approach: bool = False) -> str:
    """Generate a plausible correction suggestion based on the error text."""
    error_lower = error.lower()
    if "variable" in error_lower or "undefined" in error_lower:
        return (
            "the variable needs to be declared before use."
            if focus_on_approach
            else "Declare the variable before referencing it."
        )
    if "function" in error_lower or "call" in error_lower:
        return (
            "check the function signature and argument order."
            if focus_on_approach
            else "Verify the function name, parameters, and return handling."
        )
    if "loop" in error_lower or "infinite" in error_lower:
        return (
            "the loop condition must eventually become false."
            if focus_on_approach
            else "Add a proper termination condition to the loop."
        )
    if "index" in error_lower or "out of range" in error_lower:
        return (
            "array indices start at 0 and end at length-1."
            if focus_on_approach
            else "Check that your index is within the valid range [0, length)."
        )
    if "type" in error_lower or "casting" in error_lower:
        return (
            "ensure operands are of compatible types."
            if focus_on_approach
            else "Convert values to compatible types before operating on them."
        )
    return "review the relevant concept and double-check your logic."


def _suggest_resource(error: str) -> str:
    """Suggest a resource topic based on the error."""
    error_lower = error.lower()
    if "variable" in error_lower:
        return "the variables and scope section in your course materials"
    if "function" in error_lower:
        return "the functions and parameters reference"
    if "loop" in error_lower:
        return "the control flow and loops chapter"
    if "index" in error_lower:
        return "the arrays and indexing guide"
    if "type" in error_lower:
        return "the type system and type conversion docs"
    return "the relevant section in your learning materials"


